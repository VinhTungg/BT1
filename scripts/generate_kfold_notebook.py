            "import time\n",
            "from tqdm.auto import tqdm\n",
            "from sklearn.metrics import accuracy_score, precision_recall_fscore_support, confusion_matrix\n",
            "\n",
            "def train_epoch(model, dataloader, optimizer, scheduler, criterion, device):\n",
            "    model.train()\n",
            "    total_loss = 0.0\n",
            "    for batch in dataloader:\n",
            "        optimizer.zero_grad()\n",
            "        input_ids = batch[\"input_ids\"].to(device)\n",
            "        attention_mask = batch[\"attention_mask\"].to(device)\n",
            "        labels = batch[\"label\"].to(device)\n",
            "\n",
            "        outputs = model(input_ids=input_ids, attention_mask=attention_mask)\n",
            "        loss = criterion(outputs.logits, labels)\n",
            "        loss.backward()\n",
            "        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)\n",
            "        optimizer.step()\n",
            "        scheduler.step()\n",
            "        total_loss += loss.item()\n",
            "    return total_loss / len(dataloader)\n",
            "\n",
            "def eval_model(model, dataloader, criterion, device):\n",
            "    model.eval()\n",
            "    total_loss = 0.0\n",
            "    all_probs = []\n",
            "    all_preds = []\n",
            "    all_labels = []\n",
            "    \n",
            "    with torch.no_grad():\n",
            "        for batch in dataloader:\n",
            "            input_ids = batch[\"input_ids\"].to(device)\n",
            "            attention_mask = batch[\"attention_mask\"].to(device)\n",
            "            labels = batch[\"label\"].to(device)\n",
            "            outputs = model(input_ids=input_ids, attention_mask=attention_mask)\n",
            "            loss = criterion(outputs.logits, labels)\n",
            "            total_loss += loss.item()\n",
            "            \n",
            "            probs = torch.softmax(outputs.logits, dim=1)[:, 1].cpu().numpy()\n",
            "            preds = torch.argmax(outputs.logits, dim=1).cpu().numpy()\n",
            "            all_probs.extend(probs)\n",
            "            all_preds.extend(preds)\n",
            "            all_labels.extend(labels.cpu().numpy())\n",
            "            \n",
            "    avg_loss = total_loss / len(dataloader)\n",
            "    acc = accuracy_score(all_labels, all_preds)\n",
            "    _, _, f1_macro, _ = precision_recall_fscore_support(all_labels, all_preds, average=\"macro\", zero_division=0)\n",
            "    p_tox, r_tox, f1_tox, _ = precision_recall_fscore_support(all_labels, all_preds, average=\"binary\", pos_label=1, zero_division=0)\n",
            "    \n",
            "    return {\n",
            "        \"loss\": avg_loss,\n",
            "        \"accuracy\": acc,\n",
            "        \"macro_f1\": f1_macro,\n",
            "        \"f1_toxic\": f1_tox,\n",
            "        \"recall_toxic\": r_tox,\n",
            "        \"precision_toxic\": p_tox,\n",
            "        \"probs\": np.array(all_probs),\n",
            "        \"preds\": np.array(all_preds)\n",
            "    }"
